/* 设置全刷周期：每 val 次刷新做一次全刷；val<=0 等效 1（每次全刷） */
void epd_wave_set_part_times(int val)
{
    val = val > 0 ? val : 1;
    rt_base_t level = rt_hw_interrupt_disable();
    if (g_part_disp_times != val)
    {
        g_part_disp_times = val;
        s_since_full = 0;
    }
    rt_hw_interrupt_enable(level);
}

/* 获取当前全刷周期 */
int epd_wave_get_part_times(void)
{
    rt_base_t level = rt_hw_interrupt_disable();
    int times = g_part_disp_times;
    rt_hw_interrupt_enable(level);
    return times;
}

/* 请求下一次刷新强制全刷（一次性） */
void epd_wave_request_full(void)
{
    rt_base_t level = rt_hw_interrupt_disable();
    s_force_full = 1;
    rt_hw_interrupt_enable(level);
}

void epd_wave_submit_frame(EpdDrawMode mode)
{
    rt_base_t level = rt_hw_interrupt_disable();
    RT_ASSERT(s_frame_count < EPD_FRAME_MODE_CAPACITY);
    if (s_force_full)
    {
        mode = EPD_DRAW_MODE_FULL;
        s_force_full = 0;
    }
    s_frame_modes[(s_frame_head + s_frame_count) % EPD_FRAME_MODE_CAPACITY] = mode;
    ++s_frame_count;
    rt_hw_interrupt_enable(level);
}

